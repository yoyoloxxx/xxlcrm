import { chromium } from "playwright";
const errs = [];
const browser = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium" });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
page.on("pageerror", e => errs.push(String(e).slice(0, 250)));
await page.goto("file:///home/claude/xxlcrm-shell/dist/index.html");
await page.waitForTimeout(1000);
await page.screenshot({ path: "shots/s1-myday.png" });
const nav = async (t, f) => { await page.locator("aside").getByText(t).click(); await page.waitForTimeout(600); await page.screenshot({ path: `shots/${f}.png` }); };
await nav("Сделки", "s2-deals-kanban");
await page.getByText("Таблица", { exact: true }).click();
await page.waitForTimeout(500);
await page.screenshot({ path: "shots/s3-deals-table.png" });
await nav("Входящие", "s4-inbox");
await nav("Дашборд", "s5-dashboard");
await nav("Автоматизации", "s6-automations");
await nav("Настройки", "s7-settings");
await nav("Компании", "s8-companies");
// проверка: неактивные кнопки ничего не делают
await page.getByRole("button", { name: /Компания$/ }).click();
await page.waitForTimeout(300);
const still = (await page.textContent("body")).includes("8 записей");
console.log("inert ok:", still, "| errors:", errs.length ? errs : "none");
await browser.close();
